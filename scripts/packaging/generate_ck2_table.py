#!/usr/bin/env python3
"""Generate src/app/ck2_files.gen.hpp — the pinned CorridorKey 2.0 asset table.

Sources of truth (mirrored 1:1 from official scripts/download_weights.py):
  - weights/  : HF nikopueringer/CorridorKey2.0 (main)
  - vfms/cradio/C-RADIOv4-SO400M : HF nvidia/C-RADIOv4-SO400M @ pinned revision
  - vfms/moge/model.pt : HF Ruicheng/moge-2-vitb-normal @ pinned revision
  - vfms/rvm/*.npz     : Google DeepMind GCS bucket

Sizes are taken from a validated local copy of the official clone (the same
tree that passed the worker E2E), so the C++ fetcher verifies resume/present
checks against exactly what the pipeline loaded.

Usage: python scripts/packaging/generate_ck2_table.py <official_clone_dir>
"""
from __future__ import annotations

import sys
from pathlib import Path

CORRIDORKEY_REPO = "nikopueringer/CorridorKey2.0"
CRADIO_REPO = "nvidia/C-RADIOv4-SO400M"
CRADIO_REVISION = "c0457f5dc26ca145f954cd4fc5bb6114e5705ad8"
MOGE_REPO = "Ruicheng/moge-2-vitb-normal"
MOGE_REVISION = "ca5f0e07ff01d3e5a364c1d954ed12ee1814b368"
RVM_FILE = "pretrain_rvm_small16_256_204031069.npz"
RVM_URL = f"https://storage.googleapis.com/representations4d/checkpoints/{RVM_FILE}"

EXCLUDE_PARTS = {".cache", "__pycache__"}


def hf_url(repo: str, revision: str, rel: str) -> str:
    return f"https://huggingface.co/{repo}/resolve/{revision}/{rel}"


def iter_files(root: Path) -> list[tuple[str, str, int]]:
    out: list[tuple[str, str, int]] = []

    wroot = root / "weights"
    for name in ("corridorkey_v2.safetensors", "foundation_stats.safetensors"):
        p = wroot / name
        out.append((f"weights/{name}", hf_url(CORRIDORKEY_REPO, "main", name), p.stat().st_size))

    croot = root / "vfms" / "cradio" / "C-RADIOv4-SO400M"
    for p in sorted(croot.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(croot).as_posix()
        if any(part in EXCLUDE_PARTS for part in p.relative_to(croot).parts):
            continue
        out.append((f"vfms/cradio/C-RADIOv4-SO400M/{rel}",
                    hf_url(CRADIO_REPO, CRADIO_REVISION, rel), p.stat().st_size))

    p = root / "vfms" / "moge" / "model.pt"
    out.append(("vfms/moge/model.pt",
                hf_url(MOGE_REPO, MOGE_REVISION, "model.pt"), p.stat().st_size))

    p = root / "vfms" / "rvm" / RVM_FILE
    out.append((f"vfms/rvm/{RVM_FILE}", RVM_URL, p.stat().st_size))
    return out


def main() -> int:
    root = Path(sys.argv[1]).resolve()
    files = iter_files(root)
    total = sum(f[2] for f in files)
    lines = [
        "// GENERATED by scripts/packaging/generate_ck2_table.py — do not edit by hand.",
        "// Pinned CorridorKey 2.0 asset table: relpath (forward slashes), url, size_bytes.",
        "#pragma once",
        "",
        "namespace corridorkey::app {",
        "",
        f"inline constexpr std::size_t kCk2PackFileCount = {len(files)};",
        f"inline constexpr std::uint64_t kCk2PackTotalBytes = {total}ULL;",
        "inline constexpr Ck2PackFile kCk2PackFiles[] = {",
    ]
    for rel, url, size in files:
        lines.append(f'    {{"{rel}", "{url}", {size}ULL}},')
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace corridorkey::app")
    dst = Path(__file__).resolve().parents[2] / "src" / "app" / "ck2_files.gen.hpp"
    dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {dst} files={len(files)} total_bytes={total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
